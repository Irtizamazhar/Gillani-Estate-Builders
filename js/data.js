/* Format PKR as Lac / Crore */
function formatPrice(p, purpose) {
  let s;
  if (p >= 10000000) s = (p / 10000000).toFixed(p % 10000000 ? 2 : 0).replace(/\.?0+$/, "") + " Crore";
  else if (p >= 100000) s = (p / 100000).toFixed(p % 100000 ? 1 : 0).replace(/\.0$/, "") + " Lac";
  else s = p.toLocaleString("en-PK");
  return "PKR " + s + (purpose === "rent" ? " /mo" : "");
}

